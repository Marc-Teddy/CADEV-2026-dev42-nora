const dicts: Record<Lang, Record<string, string>> = { fr, en };

interface LangCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
}

const Ctx = createContext<LangCtx | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");

  useEffect(() => {
    const saved = window.localStorage.getItem("nora-lang") as Lang | null;
    if (saved === "fr" || saved === "en") {
      // restauration différée d'un frame : cohérence avec le rendu serveur
      const id = requestAnimationFrame(() => setLangState(saved));
      return () => cancelAnimationFrame(id);
    }
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem("nora-lang", l);
    document.documentElement.lang = l;
  }, []);

  const t = useCallback((key: string) => dicts[lang][key] ?? dicts.fr[key] ?? key, [lang]);

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useLang() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useLang must be used inside LanguageProvider");
  return ctx;
}
